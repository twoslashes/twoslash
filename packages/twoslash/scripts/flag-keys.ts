import type { CompilerOptionDeclaration } from '../src/types/options'
import fs from 'node:fs/promises'
import ts from 'typescript'
import { defaultHandbookOptions } from '../src/defaults'

const tsOptionDeclarations = (ts as any).optionDeclarations as CompilerOptionDeclaration[]

async function generateFlagKeys() {
  const keys = [
    ...tsOptionDeclarations.map(i => i.name),
    ...Object.keys(defaultHandbookOptions),
  ].sort()

  await fs.writeFile('src/flag-keys.ts', `// Generated by scripts/flag-keys.ts\nexport const flagKeys = ${JSON.stringify(keys, null, 2)}`, 'utf-8')
}

function serializeDeclaration({ name, type, element }: CompilerOptionDeclaration): string {
  const serializedType = typeof type === 'string' ? `'${type}'` : `new Map(${JSON.stringify([...type])})`
  const serializedElement = element ? `, element: ${serializeDeclaration(element)}` : ''
  return `{ name: '${name}', type: ${serializedType}${serializedElement} }`
}

// TypeScript 7 no longer exposes `optionDeclarations`, so a snapshot is kept for parsing flags
async function generateOptionDeclarations() {
  const declarations = [...tsOptionDeclarations]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(i => `  ${serializeDeclaration(i)},`)

  await fs.writeFile(
    'src/option-declarations.ts',
    `// Generated by scripts/flag-keys.ts\nimport type { CompilerOptionDeclaration } from './types/options'\n\nexport const optionDeclarations: CompilerOptionDeclaration[] = [\n${declarations.join('\n')}\n]\n`,
    'utf-8',
  )
}

generateFlagKeys()
generateOptionDeclarations()
